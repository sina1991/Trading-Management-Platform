def build_command_specs():
    result = []
    for command_id, title, description, menu_id in RAW_COMMANDS:
        active = ACTIVE.get(command_id)
        result.append(CommandSpec(
            command_id, title, description, menu_id,
            "implemented" if active else "planned",
            active[0] if active else None,
            active[1] if active else (),
        ))
    return tuple(result)
